def _read_lang(code: str) -> dict:
    path = LANG_DIR / f"{code}.json"
    try:
        with path.open(encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError):
        return {}


def _load_strings() -> dict:
    strings = dict(_FALLBACK)
    strings.update(_read_lang("en"))
    for name in GLib.get_language_names():
        code = name.split(".")[0].split("_")[0]
        if code in ("C", "en"):
            break
        translated = _read_lang(code)
        if translated:
            strings.update(translated)
            break
    return strings


_STRINGS = _load_strings()


def _(key: str, **fields) -> str:
    text = _STRINGS.get(key, key)
    if fields:
        try:
            return text.format(**fields)
        except (KeyError, IndexError):
            return text
    return text

