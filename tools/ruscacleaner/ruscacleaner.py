class RuscaWindow(Adw.ApplicationWindow):
    def __init__(self, app):
        super().__init__(application=app, title="RuscaCleaner")
        self.set_default_size(560, 720)
        self.targets = build_targets()
        self.sizes = {}
        self.busy = False

        self.toasts = Adw.ToastOverlay()
        self.set_content(self.toasts)

        toolbar = Adw.ToolbarView()
        self.toasts.set_child(toolbar)

        header = Adw.HeaderBar()
        self.scan_button = Gtk.Button(icon_name="view-refresh-symbolic",
                                      tooltip_text=_("rescan_tooltip"))
        self.scan_button.connect("clicked", lambda *_: self.scan())
        header.pack_end(self.scan_button)
        toolbar.add_top_bar(header)

        page = Adw.PreferencesPage()
        toolbar.set_content(page)

        # --- intestazione ---------------------------------------------------
        hero_group = Adw.PreferencesGroup()
        hero = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=4)
        hero.add_css_class("rusca-hero")
        title = Gtk.Label(label="RuscaCleaner", xalign=0)
        title.add_css_class("title")
        subtitle = Gtk.Label(label=_("app_subtitle"), xalign=0, wrap=True)
        subtitle.add_css_class("subtitle")
        hero.append(title)
        hero.append(subtitle)
        hero_group.add(hero)
        page.add(hero_group)

        # --- selezione ------------------------------------------------------
        self.group = Adw.PreferencesGroup(title=_("group_what"))
        page.add(self.group)

        for target in self.targets:
            row = Adw.SwitchRow(title=target.title, subtitle=target.subtitle)
            row.set_active(target.default)
            row.connect("notify::active", lambda *_: self.update_total())
            target.row = row
            self.group.add(row)

        # --- azione ---------------------------------------------------------
        action_group = Adw.PreferencesGroup()
        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=12)

        self.total_label = Gtk.Label(label=_("total_pending"))
        self.total_label.add_css_class("rusca-total")
        box.append(self.total_label)

        self.clean_button = Gtk.Button(label=_("btn_clean"))
        self.clean_button.add_css_class("destructive-action")
        self.clean_button.add_css_class("pill")
        self.clean_button.set_halign(Gtk.Align.CENTER)
        self.clean_button.connect("clicked", self.on_clean_clicked)
        box.append(self.clean_button)

        self.spinner = Gtk.Spinner()
        box.append(self.spinner)

        action_group.add(box)
        page.add(action_group)

        # --- registro -------------------------------------------------------
        log_group = Adw.PreferencesGroup(title=_("group_log"))
        scroller = Gtk.ScrolledWindow(min_content_height=170, vexpand=True)
        scroller.add_css_class("card")
        self.log_view = Gtk.TextView(editable=False, cursor_visible=False,
                                     wrap_mode=Gtk.WrapMode.WORD_CHAR,
                                     top_margin=8, bottom_margin=8,
                                     left_margin=8, right_margin=8)
        self.log_view.add_css_class("rusca-log")
        scroller.set_child(self.log_view)
        log_group.add(scroller)
        page.add(log_group)

        self.log(_("ready"))
        self.scan()

    # -- utilità ------------------------------------------------------------
    def log(self, text: str):
        buf = self.log_view.get_buffer()
        buf.insert(buf.get_end_iter(), text + "\n")
        mark = buf.create_mark(None, buf.get_end_iter(), False)
        self.log_view.scroll_to_mark(mark, 0, False, 0, 0)
        buf.delete_mark(mark)

    def set_busy(self, busy: bool):
        self.busy = busy
        self.clean_button.set_sensitive(not busy)
        self.scan_button.set_sensitive(not busy)
        self.spinner.set_visible(busy)
        if busy:
            self.spinner.start()
        else:
            self.spinner.stop()

    def selected(self) -> List[Target]:
        return [t for t in self.targets if t.row.get_active()]

    # -- analisi -------------------------------------------------------------
    def scan(self):
        if self.busy:
            return
        self.set_busy(True)
        threading.Thread(target=self._scan_worker, daemon=True).start()

    def _scan_worker(self):
        sizes = {t.key: (t.size(), t.exists()) for t in self.targets}
        GLib.idle_add(self._scan_done, sizes)

    def _scan_done(self, sizes):
        self.sizes = sizes
        for target in self.targets:
            size, exists = sizes[target.key]
            if not exists:
                target.row.set_subtitle(_("no_data"))
                target.row.set_active(False)
                target.row.set_sensitive(False)
            else:
                target.row.set_sensitive(True)
                suffix = f" · {fmt(size)}" if size else " · " + _("empty")
                target.row.set_subtitle(target.subtitle + suffix)
        self.update_total()
        self.log(_("scan_done", size=fmt(self._total_bytes())))
        self.set_busy(False)
        return False

    def _total_bytes(self) -> int:
        return sum(self.sizes.get(t.key, (0, False))[0] for t in self.selected())

    def update_total(self):
        self.total_label.set_label(_("total", size=fmt(self._total_bytes())))

    # -- pulizia -------------------------------------------------------------
    def on_clean_clicked(self, _button):
        chosen = self.selected()
        if not chosen:
            self.toasts.add_toast(Adw.Toast(title=_("none_selected")))
            return

        elenco = "\n".join(f"• {t.title}" for t in chosen)
        notes = [t.note for t in chosen if t.note]
        body = _("confirm_body") + "\n\n" + elenco
        if notes:
            body += "\n\n" + "\n".join(notes)

        dialog = Adw.AlertDialog(heading=_("confirm_heading"), body=body)
        dialog.add_response("cancel", _("cancel"))
        dialog.add_response("clean", _("clean"))
        dialog.set_response_appearance("clean", Adw.ResponseAppearance.DESTRUCTIVE)
        dialog.set_default_response("cancel")
        dialog.set_close_response("cancel")
        dialog.connect("response", self.on_dialog_response, chosen)
        dialog.present(self)

    def on_dialog_response(self, _dialog, response, chosen):
        if response != "clean":
            return
        self.set_busy(True)
        self.log("")
        self.log(_("cleaning"))
        threading.Thread(target=self._clean_worker, args=(chosen,),
                         daemon=True).start()

    def _clean_worker(self, chosen: List[Target]):
        freed = 0
        for target in chosen:
            GLib.idle_add(self.log, f"{target.title}:")
            freed += target.clean(lambda msg: GLib.idle_add(self.log, msg))
        GLib.idle_add(self._clean_done, freed)

    def _clean_done(self, freed: int):
        self.log(_("done", size=fmt(freed)))
        self.toasts.add_toast(Adw.Toast(title=_("toast_freed", size=fmt(freed))))
        self.set_busy(False)
        self.scan()
        return False


class RuscaCleaner(Adw.Application):
    def __init__(self):
        super().__init__(application_id=APP_ID)

    def do_startup(self):
        Adw.Application.do_startup(self)
        provider = Gtk.CssProvider()
        if hasattr(provider, "load_from_string"):   # GTK 4.12+
            provider.load_from_string(CSS)
        else:
            provider.load_from_data(CSS.encode())
        Gtk.StyleContext.add_provider_for_display(
            Gdk.Display.get_default(),
            provider,
            Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION,
        )

    def do_activate(self):
        window = self.props.active_window or RuscaWindow(self)
        window.present()


if __name__ == "__main__":
    # Sotto sudo Path.home() è /root: l'app pulirebbe in silenzio la home
    # sbagliata, e all'utente sembrerebbe soltanto che non abbia funzionato.
    if os.geteuid() == 0 and os.environ.get("SUDO_USER"):
        print(_("err_sudo"), file=sys.stderr)
        sys.exit(1)
    RuscaCleaner().run(None)
